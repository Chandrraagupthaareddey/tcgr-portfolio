#!/usr/bin/env node
/**
 * gen-schemas.js — regenerates apps-script/Schemas.js from FALLBACK_DATA in
 * public/assets/app.js, so the bundled fallback and the Sheet seed never drift.
 *
 *   node tools/gen-schemas.js
 *
 * Shapes:
 *   object  → key/value sheet (headers: key, value)
 *   array of objects → tabular sheet (headers = union of keys, in first-seen order)
 *   array of strings → one-column sheet (header: item)
 *   nested arrays inside a row → joined with " ; "
 */
'use strict';
const fs = require('fs');
const path = require('path');
const vm = require('vm');

const root = path.join(__dirname, '..');
const appJs = fs.readFileSync(path.join(root, 'public/assets/app.js'), 'utf8');

// Extract the FALLBACK_DATA literal and evaluate it in isolation.
const start = appJs.indexOf('const FALLBACK_DATA = {');
const end = appJs.indexOf('\n};', start) + 3;
if (start < 0 || end < 3) throw new Error('FALLBACK_DATA not found in app.js');
const ctx = {};
vm.createContext(ctx);
vm.runInContext(appJs.slice(start, end) + '\nthis.__data = FALLBACK_DATA;', ctx);
const data = ctx.__data;

const SKIP = new Set(['meta']); // meta is maintained by hand (version marker)
const toCell = v => Array.isArray(v) ? v.join(' ; ') : (v === null || v === undefined ? '' : v);

const sheets = {};
for (const [name, value] of Object.entries(data)) {
  if (SKIP.has(name)) continue;
  if (Array.isArray(value)) {
    if (value.length && typeof value[0] === 'string') {
      sheets[name] = { headers: ['item'], rows: value.map(v => [v]) };
    } else {
      const headers = [];
      value.forEach(r => Object.keys(r).forEach(k => { if (!headers.includes(k)) headers.push(k); }));
      sheets[name] = { headers, rows: value.map(r => headers.map(h => toCell(r[h]))) };
    }
  } else if (value && typeof value === 'object') {
    sheets[name] = { headers: ['key', 'value'], rows: Object.entries(value).map(([k, v]) => [k, toCell(v)]) };
  }
}
sheets.meta = { headers: ['key', 'value'], rows: [['version', '2.0.0'], ['last_updated', '__TODAY__'], ['domain', 'tcgr.in']] };

const lit = v => JSON.stringify(v);
let out = `/**
 * ============================================================================
 *  Schemas.js — Sheet schema definitions and bootstrap  (GENERATED)
 *  ============================================================================
 *  Generated by tools/gen-schemas.js from FALLBACK_DATA in public/assets/app.js.
 *  Do not edit the seed rows by hand — edit FALLBACK_DATA and regenerate.
 *
 *  setupSheets()        — idempotent: adds any sheet that is missing.
 *  reseedSheet(name)    — overwrites one sheet with its seed rows.
 *  ============================================================================
 */

function setupSheets() {
  const ss = SpreadsheetApp.getActiveSpreadsheet();
  const schemas = _SCHEMAS();
  let created = 0;
  Object.keys(schemas).forEach(name => {
    if (!ss.getSheetByName(name)) { _writeSheet(ss.insertSheet(name), schemas[name]); created++; }
  });
  const def = ss.getSheetByName('Sheet1');
  if (def && !schemas.Sheet1 && ss.getSheets().length > 1) ss.deleteSheet(def);
  ss.toast('Schema initialized · ' + created + ' sheet(s) created ✓', 'tcgr.in CMS', 5);
}

function reseedSheet(name) {
  const ss = SpreadsheetApp.getActiveSpreadsheet();
  const schema = _SCHEMAS()[name];
  if (!schema) throw new Error('No schema for sheet: ' + name);
  const sh = ss.getSheetByName(name) || ss.insertSheet(name);
  sh.clear();
  _writeSheet(sh, schema);
}

function _writeSheet(sh, schema) {
  const { headers, rows } = schema;
  sh.getRange(1, 1, 1, headers.length).setValues([headers]).setFontWeight('bold').setBackground('#0b0e12').setFontColor('#f2b84b');
  if (rows && rows.length) sh.getRange(2, 1, rows.length, headers.length).setValues(rows.map(r => r.map(c => c === '__TODAY__' ? new Date().toISOString().slice(0, 10) : c)));
  sh.setFrozenRows(1);
  try { sh.autoResizeColumns(1, headers.length); } catch (e) {}
}

function _SCHEMAS() {
  return {
`;
for (const [name, s] of Object.entries(sheets)) {
  out += `    ${name}: {\n      headers: ${lit(s.headers)},\n      rows: [\n`;
  out += s.rows.map(r => `        ${lit(r)}`).join(',\n');
  out += `\n      ]\n    },\n`;
}
out = out.replace(/,\n$/, '\n');
out += `  };
}
`;
fs.writeFileSync(path.join(root, 'apps-script/Schemas.js'), out);
console.log(`✓ Schemas.js regenerated: ${Object.keys(sheets).length} sheets`);
